/** Offline, reproducible extraction of the exact Lucide artifact Fancy resolves. */
import { createRequire } from 'node:module';
import { existsSync } from 'node:fs';
import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises';
import { dirname, resolve, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';

const ui = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const php = resolve(ui, '../fancy-cms');
const hasPHP = existsSync(join(php, 'composer.json'));
const require = createRequire(join(ui, 'package.json'));
const tags = new Set(['circle', 'ellipse', 'line', 'path', 'polygon', 'polyline', 'rect']);
const attributes = new Set(['cx', 'cy', 'd', 'fill', 'height', 'points', 'r', 'rx', 'ry', 'width', 'x', 'x1', 'x2', 'y', 'y1', 'y2']);
const sortEntries = object => Object.fromEntries(Object.entries(object).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0));
const json = value => JSON.stringify(value);
const banner = '// Generated by scripts/generate-icons.mjs. Lucide ISC; see licenses/LUCIDE-LICENSE and NOTICE.\n';
const declaration = 'type Glyph = readonly (readonly [string, Readonly<Record<string, string | number>>])[];\n';

// Version override is only used by the regression test to simulate installed
// source drift. The CLI has no override and always reads the installed artifact.
export async function createArtifacts({ lucideVersion } = {}) {
  const fancyPath = resolve(require.resolve('@particle-academy/react-fancy'), '../../package.json');
  const fancy = JSON.parse(await readFile(fancyPath, 'utf8'));
  const lucideRoot = resolve(require.resolve('lucide-react', { paths: [fancyPath] }), '../../..');
  const source = JSON.parse(await readFile(join(lucideRoot, 'package.json'), 'utf8'));
  const version = lucideVersion ?? source.version;
  const dynamic = await readFile(join(lucideRoot, 'dist/esm/dynamicIconImports.js'), 'utf8');
  const names = {};
  for (const match of dynamic.matchAll(/"([a-z0-9-]+)": \(\) => import\('\.\/icons\/([a-z0-9-]+)\.js'\)/g)) {
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(match[1]) || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(match[2])) throw new Error('Unsafe Lucide name.');
    if (Object.hasOwn(names, match[1])) throw new Error('Duplicate Lucide name.');
    names[match[1]] = match[2];
  }
  if (Object.keys(names).length === 0 || ['index', 'all', 'metadata', 'glyph'].some(name => Object.hasOwn(names, name))) throw new Error('Unsupported Lucide catalogue.');
  const orderedNames = sortEntries(names);
  const glyphs = {};
  for (const canonical of [...new Set(Object.values(orderedNames))].sort()) {
    const { __iconNode } = await import(pathToFileURL(join(lucideRoot, 'dist/esm/icons', `${canonical}.js`)));
    if (!Array.isArray(__iconNode) || __iconNode.length === 0) throw new Error(`Missing icon data: ${canonical}`);
    glyphs[canonical] = __iconNode.map(primitive => {
      if (!Array.isArray(primitive) || primitive.length !== 2) throw new Error('Invalid SVG primitive.');
      const [tag, values] = primitive;
      if (!tags.has(tag) || !values || typeof values !== 'object' || Array.isArray(values)) throw new Error('Unsupported SVG primitive.');
      const attrs = {};
      for (const [key, value] of Object.entries(values)) {
        if (key === 'key') continue;
        if (!attributes.has(key) || !['string', 'number'].includes(typeof value)) throw new Error('Unsupported SVG attribute.');
        if (typeof value === 'number' ? !Number.isFinite(value) : (key === 'fill' ? !['none', 'currentColor'].includes(value) : !/^[A-Za-z0-9+.,\s-]*$/.test(value))) throw new Error('Unsafe SVG value.');
        attrs[key] = value;
      }
      return [tag, sortEntries(attrs)];
    });
  }
  const hash = createHash('sha256').update(json({ version, names: orderedNames, glyphs })).digest('hex');
  const metadata = { source: 'lucide-react', version, reactFancyVersion: fancy.version, lucideRange: fancy.dependencies['lucide-react'], names: Object.keys(orderedNames).length, glyphs: Object.keys(glyphs).length, hash };
  const license = await readFile(join(lucideRoot, 'LICENSE'), 'utf8');
  const notice = `Lucide icon data\nSource: lucide-react@${version}, https://github.com/lucide-icons/lucide\nExtracted from the published package resolved by @particle-academy/react-fancy@${fancy.version} (${metadata.lucideRange}).\nCopyright (c) Lucide Contributors 2022; portions Cole Bemis 2013-2022 / Feather (MIT).\nISC licence reproduced in licenses/LUCIDE-LICENSE. React keys removed; SVG attributes sorted.\nCanonical content SHA256: ${hash}\n`;
  const artifacts = new Map();
  const add = (root, path, contents) => artifacts.set(join(root, path).replaceAll('\\', '/'), contents);
  for (const root of [ui, ...(hasPHP ? [php] : [])]) {
    add(root, 'licenses/LUCIDE-LICENSE', license);
    add(root, 'NOTICE', notice);
  }
  add(ui, 'icons/metadata.json', json(metadata) + '\n');
  if (hasPHP) {
    add(php, 'resources/icons/metadata.json', json(metadata) + '\n');
    add(php, 'resources/icons/index.json', json(orderedNames) + '\n');
  }
  add(ui, 'src/document/icon-names.ts', banner + `export const ICON_SOURCE = ${json(`lucide-react@${version}`)};\nexport const ICON_NAMES: readonly string[] = Object.freeze(${json(Object.keys(orderedNames))});\n`);
  add(ui, 'icons/glyph.d.ts', declaration + 'declare const glyph: Glyph;\nexport default glyph;\n');
  add(ui, 'icons/glyph.d.cts', declaration + 'declare const glyph: Glyph;\nexport = glyph;\n');
  const allImports = [], allRequire = [], allNames = [];
  const canonicalIDs = new Map(Object.keys(glyphs).map((name, index) => [name, `g${index}`]));
  for (const [name, glyph] of Object.entries(glyphs)) {
    add(ui, `icons/${name}.js`, banner + `export default ${json(glyph)};\n`);
    add(ui, `icons/${name}.cjs`, banner + `module.exports = ${json(glyph)};\n`);
    if (hasPHP) add(php, `resources/icons/glyphs/${name}.json`, json(glyph) + '\n');
    const id = canonicalIDs.get(name);
    allImports.push(`import ${id} from './${name}.js';`);
    allRequire.push(`const ${id} = require('./${name}.cjs');`);
  }
  for (const [name, canonical] of Object.entries(orderedNames)) {
    allNames.push(`${json(name)}:${canonicalIDs.get(canonical)}`);
    if (name !== canonical) {
      add(ui, `icons/${name}.js`, banner + `export {default} from './${canonical}.js';\n`);
      add(ui, `icons/${name}.cjs`, banner + `module.exports = require('./${canonical}.cjs');\n`);
    }
  }
  add(ui, 'icons/all.js', banner + allImports.join('\n') + `\nexport default {${allNames.join(',')}};\n`);
  add(ui, 'icons/all.cjs', banner + allRequire.join('\n') + `\nmodule.exports = {${allNames.join(',')}};\n`);
  add(ui, 'icons/all.d.ts', declaration + 'declare const icons: Readonly<Record<string, Glyph>>;\nexport default icons;\n');
  add(ui, 'icons/all.d.cts', declaration + 'declare const icons: Readonly<Record<string, Glyph>>;\nexport = icons;\n');
  // This entry alone owns the dynamic graph. Static consumers never import it.
  const loaders = Object.keys(glyphs).map(name => `${json(name)}:()=>import('./${name}.js')`).join(',\n');
  const cjsLoaders = Object.keys(glyphs).map(name => `${json(name)}:()=>Promise.resolve().then(()=>({default:require('./${name}.cjs')}))`).join(',\n');
  const loaderBody = `const aliases=${json(orderedNames)};\nasync function loadIcons(names){\n const requested=[...new Set(names)];\n if(requested.some(name=>typeof name!=='string'||!Object.hasOwn(aliases,name)))throw new TypeError('Unknown icon name.');\n const loaded=await Promise.all(requested.map(async name=>[name,(await loaders[aliases[name]]()).default]));\n return Object.fromEntries(loaded);\n}\n`;
  add(ui, 'icons/index.js', banner + `const loaders={${loaders}};\n` + loaderBody + 'export {loadIcons};\n');
  add(ui, 'icons/index.cjs', banner + `const loaders={${cjsLoaders}};\n` + loaderBody + 'exports.loadIcons=loadIcons;\n');
  const loaderDecl = declaration + 'export declare function loadIcons(names: Iterable<string>): Promise<Record<string, Glyph>>;\n';
  add(ui, 'icons/index.d.ts', loaderDecl);
  add(ui, 'icons/index.d.cts', loaderDecl);
  return artifacts;
}

export async function verifyArtifacts(artifacts, read = path => readFile(path, 'utf8')) {
  const entries = [...artifacts];
  for (let start = 0; start < entries.length; start += 64) {
    await Promise.all(entries.slice(start, start + 64).map(async ([path, expected]) => {
      let actual;
      try { actual = await read(path); } catch { throw new Error(`Icon artifact drift: missing ${path}`); }
      if (actual !== expected) throw new Error(`Icon artifact drift: ${path}`);
    }));
  }
  for (const directory of [join(ui, 'icons'), ...(hasPHP ? [join(php, 'resources/icons/glyphs')] : [])]) {
    for (const name of await readdir(directory)) {
      if (!artifacts.has(join(directory, name).replaceAll('\\', '/'))) throw new Error(`Icon artifact drift: unexpected ${name}`);
    }
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.some(arg => !['--check', '--require-twin'].includes(arg)) || new Set(args).size !== args.length) throw new Error('Use generate-icons.mjs [--check] [--require-twin].');
  if (args.includes('--require-twin') && !hasPHP) throw new Error('PHP twin required for the paired release check.');
  const artifacts = await createArtifacts();
  if (args.includes('--check')) await verifyArtifacts(artifacts);
  else {
    // No recursive deletion: regeneration refuses stale files in check mode.
    const entries = [...artifacts];
    for (const directory of new Set(entries.map(([path]) => dirname(path)))) await mkdir(directory, { recursive: true });
    for (let start = 0; start < entries.length; start += 64) await Promise.all(entries.slice(start, start + 64).map(([path, contents]) => writeFile(path, contents)));
    await verifyArtifacts(artifacts);
  }
  process.stdout.write(`Icon artifacts ${args.includes('--check') ? 'verified' : 'generated'}: ${artifacts.size} files, ${hasPHP ? 'PHP + JS' : 'JS only (PHP twin absent)'}, offline.\n`);
}
