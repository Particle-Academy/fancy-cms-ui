/** Uses the workspace's installed first-party browser tools; adds no dependency. */
import assert from "node:assert/strict";
import http from "node:http";
import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { CmsPage } from "../dist/react.js";
import { emitDocCss } from "../dist/index.js";
import icons from "../icons/all.js";
import { chromium } from "../../fancy-labs/vendor/particle-academy/prism-browser/sidecar/node_modules/playwright/index.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const fixturePath = resolve(here, "canonical-csp-icons.json");
const doc = JSON.parse(readFileSync(fixturePath, "utf8"));
const php = (script) => execFileSync(process.env.FANCY_CMS_PHP || "php", [resolve(here, `../../fancy-cms/bin/${script}.php`), fixturePath], { encoding: "utf8" });
const phpHtml = php("render-html"), phpCss = php("emit-css");
const jsHtml = renderToStaticMarkup(createElement(CmsPage, { doc, icons, includeStyles: false }));
assert.equal(phpHtml, jsHtml);
assert.equal(phpCss, emitDocCss(doc));
assert.ok(!/\sstyle\s*=/i.test(phpHtml));
// Actual flabs response policy, generated by its offline feature suite.
const flabs = JSON.parse(readFileSync(resolve(here, "../../fancy-labs/storage/framework/testing/site-image-security/fixture.json"), "utf8"));
assert.match(flabs.csp, /script-src 'none'/);
const nonce = flabs.csp.match(/style-src 'nonce-([a-f0-9]+)'/)[1];
const html = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><style nonce="${nonce}">${phpCss}</style></head><body>${phpHtml}</body></html>`;
const output = resolve(here, "../../../sandbox/cms-no-inline-browser");
mkdirSync(output, { recursive: true });
const server = http.createServer((request, response) => {
  if (request.url === "/favicon.ico") { response.writeHead(204); response.end(); return; }
  response.writeHead(200, { "Content-Type": "text/html; charset=UTF-8", "Content-Security-Policy": flabs.csp });
  response.end(html);
});
let browser;
const results = [];
try {
  await new Promise(resolve => server.listen(0, "127.0.0.1", resolve));
  const origin = `http://127.0.0.1:${server.address().port}`;
  browser = await chromium.launch({ headless: true });
  for (const width of [375, 768, 1280]) {
    const page = await browser.newPage({ viewport: { width, height: 900 }, deviceScaleFactor: 1 });
    const errors = [], offOrigin = [];
    page.on("pageerror", error => errors.push(error.message));
    page.on("console", message => { if (message.type() === "error") errors.push(message.text()); });
    await page.route("**/*", route => {
      if (new URL(route.request().url()).origin !== origin) { offOrigin.push(route.request().url()); return route.abort(); }
      return route.continue();
    });
    await page.goto(origin, { waitUntil: "networkidle" });
    const boxes = await page.evaluate(() => [...document.querySelectorAll("[data-react-fancy-icon]")].map(element => ({
      id: element.parentElement.getAttribute("data-cms"), width: element.getBoundingClientRect().width,
      height: element.getBoundingClientRect().height, fontSize: parseFloat(getComputedStyle(element).fontSize),
      display: getComputedStyle(element).display, align: getComputedStyle(element).alignItems,
      justify: getComputedStyle(element).justifyContent, shrink: getComputedStyle(element).flexShrink,
      inline: element.hasAttribute("style"), svgWidth: element.querySelector("svg").getBoundingClientRect().width,
    })));
    assert.equal(boxes.length, 2);
    for (const box of boxes) {
      assert.equal(box.inline, false); assert.equal(box.display, "inline-flex");
      assert.equal(box.align, "center"); assert.equal(box.justify, "center"); assert.equal(box.shrink, "0");
      assert.equal(box.width, box.fontSize); assert.equal(box.height, box.fontSize); assert.equal(box.svgWidth, box.fontSize);
      assert.equal(box.fontSize, { 375: { small: 12, large: 24 }, 768: { small: 20, large: 32 }, 1280: { small: 24, large: 40 } }[width][box.id]);
    }
    assert.deepEqual(errors, []); assert.deepEqual(offOrigin, []);
    await page.screenshot({ path: resolve(output, `${width}.png`), fullPage: true });
    results.push({ width, boxes, consoleErrors: errors, offOrigin });
    await page.close();
  }
  writeFileSync(resolve(output, "evidence.json"), JSON.stringify({ status: "PASS", policy: flabs.csp, results }, null, 2));
  console.log(JSON.stringify({ status: "PASS", widths: results.map(result => result.width), output }, null, 2));
} finally {
  if (browser) await browser.close();
  server.closeAllConnections();
  await new Promise(resolve => server.close(resolve));
}
